"""Dimension definition used by indexed workbench research."""
DIMENSION_DEFINITION='''维度的定义与要求：
维度是围绕研究问题，将回答同一方面问题、具有共同分析焦点的发现组织起来的分类。维度用于呈现发现之间的结构，不新增事实、因果或理论结论，也不替代具体发现。
每个维度有明确焦点，说明它集中回答什么问题。同一维度内部有实质联系，不仅是关键词相同；不同维度应有可区分的边界。
划分角度一致：同一研究问题下，同一级维度应采用一致的主要划分依据，例如按涉及对象、行为领域或过程阶段划分，不混用不同依据。归纳前明确所采用的划分角度，并据此说明各维度的边界；不得为保持形式一致而扭曲发现或强行归类。使用过程阶段必须有材料支持，不能凭空添加先后关系。
维度名称简洁具体，可以是名词短语，不必写成完整陈述；每个维度附简短定义，说明纳入哪些内容以及容易混淆但不属于它的内容。
不预设维度数量、不强凑均衡，不要求各维度发现数量相同；重要的独立发现可以单独形成维度，不使用“其他”或“相关发现”作为兜底类别。
直接将发现归入维度，不强制增加中间层。不改写发现、概括及证据；每条发现应恰好归入一个最合适维度，或明确列为“暂无分类”并简要说明原因。无法合理归纳时不得强行归纳。已分类与暂无分类合计必须完整覆盖全部发现，不能遗漏、重复或新增。'''
